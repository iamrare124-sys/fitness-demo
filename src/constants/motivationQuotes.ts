export type QuoteCategory = keyof typeof MOTIVATION_QUOTES;

export function getRandomQuote(category: QuoteCategory = 'mindset'): string {
  const quotes = MOTIVATION_QUOTES[category];
  const index = Math.floor(Math.random() * quotes.length);
  return quotes[index] ?? quotes[0];
}

export function getDailyQuote(category: QuoteCategory = 'mindset'): string {
  // Returns the same quote for the whole day (deterministic by date + category)
  const today = new Date().toDateString();
  let hash = 0;
  for (let i = 0; i < today.length; i++) {
    hash = ((hash << 5) - hash) + today.charCodeAt(i);
    hash |= 0;
  }
  const quotes = MOTIVATION_QUOTES[category];
  const index = Math.abs(hash) % quotes.length;
  return quotes[index] ?? quotes[0];
}
